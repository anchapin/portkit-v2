"""Java -> Bedrock vanilla item ids, fetched on demand (#261).

A Java recipe names vanilla items by their Java ids, and many of those are
spelled differently on Bedrock: Java ``minecraft:bricks`` / ``minecraft:lily_pad``
/ ``minecraft:oak_button`` / ``minecraft:terracotta`` are Bedrock
``minecraft:brick_block`` / ``minecraft:waterlily`` / ``minecraft:wooden_button``
/ ``minecraft:hardened_clay``, and Java's sixteen ``minecraft:<colour>_bed`` are
Bedrock's one ``minecraft:bed`` told apart by a data value. Bedrock Dedicated
Server refuses a recipe naming an id it doesn't know ("The Item: minecraft:bricks
is missing or invalid, can't make the recipe"), so the converter rewrites them.

The table comes from GeyserMC/mappings ``items.json`` (the Java -> Bedrock item
map Geyser's proxy uses, generated by GeyserMC's mappings-generator for Java
Edition 26.3 and Bedrock Edition 1.26.50 at the pinned commit). The file is MIT
licensed by GeyserMC, which says it does not relicense Minecraft's own data; so,
like Mojang's lists, it is never vendored: ``portkit reference fetch`` downloads
it at the pinned commit, keeps only what the converter needs (see
:func:`derive`), checks the result against :data:`SHA256` and caches it.

What :func:`derive` keeps:

* ``renamed``: every Java id whose Bedrock id differs, as ``{"id": <bedrock id>}``,
  plus ``"data"`` when that Bedrock id stands for more than one Java item (beds,
  banners), the value Geyser gives (``bedrock_data``, 0 when absent). A Java id
  Geyser maps to itself is left out: its Bedrock id is the same (Geyser's legacy
  data values on flattened ids, like ``spruce_planks`` 1, aren't recipe data).
* ``ambiguous``: Java ids whose Bedrock id and data are shared with another Java
  item (``tipped_arrow`` and ``spectral_arrow`` are both plain ``arrow``; every
  explorer map is ``filled_map``), each with the ids it is shared with. A recipe
  naming one can't be written without turning it into the other item, so it
  stays residue.

Without the table, :func:`table` returns None and recipes keep vanilla ids as
written (the conversion notes say to run the fetch). ``PORTKIT_JAVA_ITEMS``
names a derived table (JSON) to use instead, unverified: it is how the tests
run offline.

``python -m portkit.data.java_items --pin`` downloads it and prints the sha256.
"""
from __future__ import annotations

import hashlib
import json
import os
import sys
import urllib.request
from collections import defaultdict
from dataclasses import dataclass
from functools import lru_cache
from pathlib import Path

from . import ReferenceDataError, _USER_AGENT, cache_dir

_ENV_FILE = "PORTKIT_JAVA_ITEMS"

SET_ID = "java-bedrock-items"
REPO = "GeyserMC/mappings"
COMMIT = "81700ab543c1f4e9f9041f58dac4154ecb0d0c8b"
SOURCE = "items.json"
URL = f"https://raw.githubusercontent.com/{REPO}/{COMMIT}/{SOURCE}"
LABEL = f"Java -> Bedrock item ids, {REPO}@{COMMIT[:12]} (MIT; Java 26.3 / Bedrock 1.26.50)"

# sha256 of the derived table (see derive); bump it together with COMMIT.
SHA256 = "fcf7f60475aa6a96d0059e37320dd001d33e700c5fd70659d9e70b619844e944"


def derive(raw: bytes) -> bytes:
    """items.json -> the renamed and ambiguous Java ids, as sorted JSON."""
    data = json.loads(raw)
    if not isinstance(data, dict) or not data:
        raise ValueError("items.json is not a non-empty object")
    target: dict[str, tuple[str, int | None]] = {}
    for java, entry in data.items():
        bedrock = entry.get("bedrock_identifier") if isinstance(entry, dict) else None
        if not isinstance(java, str) or not isinstance(bedrock, str):
            continue
        value = entry.get("bedrock_data")
        target[java] = (bedrock, value if isinstance(value, int) else None)
    if not target:
        raise ValueError("no item mappings in items.json")
    by_id: dict[str, list[str]] = defaultdict(list)
    by_pair: dict[tuple[str, int], list[str]] = defaultdict(list)
    for java, (bedrock, value) in target.items():
        by_id[bedrock].append(java)
        by_pair[(bedrock, value or 0)].append(java)
    renamed: dict[str, dict] = {}
    ambiguous: dict[str, list[str]] = {}
    for java, (bedrock, value) in sorted(target.items()):
        if bedrock == java:
            continue
        shared = sorted(j for j in by_pair[(bedrock, value or 0)] if j != java)
        if shared:
            ambiguous[java] = shared
            continue
        entry = {"id": bedrock}
        if len(by_id[bedrock]) > 1:
            entry["data"] = value or 0
        renamed[java] = entry
    out = {
        "source": f"{REPO}@{COMMIT} {SOURCE}",
        "renamed": renamed,
        "ambiguous": ambiguous,
    }
    return (json.dumps(out, indent=1, sort_keys=True) + "\n").encode("utf-8")


def _sha256(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def set_path(cache: Path | None = None) -> Path:
    return Path(cache or cache_dir()) / f"{SET_ID}-{SHA256[:12]}.json"


def cached(cache: Path | None = None) -> Path | None:
    """The verified cached table, or None when it is missing or doesn't match the pin."""
    path = set_path(cache)
    return path if path.is_file() and _sha256(path.read_bytes()) == SHA256 else None


def download(opener=urllib.request.urlopen) -> bytes:
    """The derived table, straight from upstream (unverified)."""
    request = urllib.request.Request(URL, headers={"User-Agent": _USER_AGENT})
    try:
        with opener(request, timeout=120) as response:
            raw = response.read()
    except (OSError, ValueError, AttributeError) as exc:
        raise ReferenceDataError(f"{SET_ID}: download failed from {URL}: {exc}") from exc
    try:
        return derive(raw)
    except (ValueError, AttributeError, TypeError, KeyError) as exc:
        raise ReferenceDataError(f"{SET_ID}: could not read {SOURCE}: {exc}") from exc


def fetch(cache: Path | None = None, opener=urllib.request.urlopen) -> tuple[Path, bool]:
    """Return (cached path, downloaded?). Raises ReferenceDataError on failure or a hash mismatch."""
    cache = Path(cache or cache_dir())
    hit = cached(cache)
    if hit:
        return hit, False
    data = download(opener)
    digest = _sha256(data)
    if digest != SHA256:
        raise ReferenceDataError(
            f"{SET_ID}: sha256 mismatch for {URL} (got {digest[:16]}..., "
            f"pinned {SHA256[:16]}...); re-pin it on purpose"
        )
    cache.mkdir(parents=True, exist_ok=True)
    target = set_path(cache)
    partial = target.with_suffix(".part")
    partial.write_bytes(data)
    partial.replace(target)
    _read.cache_clear()
    return target, True


@dataclass(frozen=True)
class Table:
    """The derived table: Java id -> Bedrock id (and data), and the ids that can't map."""

    renamed: dict
    ambiguous: dict

    def lookup(self, java: str) -> tuple[str, int | None] | None:
        """(Bedrock id, data or None) for a renamed Java id, else None."""
        entry = self.renamed.get(java)
        if not isinstance(entry, dict) or not isinstance(entry.get("id"), str):
            return None
        data = entry.get("data")
        return entry["id"], data if isinstance(data, int) else None


@lru_cache(maxsize=4)
def _read(path: str, mtime_ns: int, size: int, verify: bool) -> Table | None:
    data = Path(path).read_bytes()
    if verify and _sha256(data) != SHA256:
        return None
    try:
        body = json.loads(data)
    except ValueError:
        return None
    if not isinstance(body, dict):
        return None
    return Table(dict(body.get("renamed") or {}), dict(body.get("ambiguous") or {}))


def table() -> Table | None:
    """The Java -> Bedrock item table, or None when it isn't cached
    (run ``portkit reference fetch``)."""
    override = os.environ.get(_ENV_FILE)
    path = Path(override).expanduser() if override else set_path()
    try:
        stat = path.stat()
    except OSError:
        return None
    return _read(str(path), stat.st_mtime_ns, stat.st_size, not override)


def main(argv: list[str] | None = None) -> int:
    args = sys.argv[1:] if argv is None else argv
    if args != ["--pin"]:
        print("usage: python -m portkit.data.java_items --pin", file=sys.stderr)
        return 2
    print(_sha256(download()))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
